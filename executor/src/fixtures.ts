export function transfer(
  id: string,
  cents: bigint,
  to: Address = COLD_VAULT,
  at = 0,
  over: Partial<TransferRequest> = {},
): TransferRequest {
  return {
    ...envelope(id, at),
    kind: "transfer",
    contract: COLLECTION,
    subject: tokenIdSubject("1"),
    to,
    valuation: usd(cents),
    ...over,
  };
}

/** An SPL transfer: a fungible amount out of a mint, to a Solana destination. */
export function solanaTransfer(
  id: string,
  cents: bigint,
  to: Address = SOL_COLD_VAULT,
  at = 0,
  over: Partial<TransferRequest> = {},
): TransferRequest {
  return {
    ...envelope(id, at, SOL_CHAIN, SOL_ACCOUNT),
    kind: "transfer",
    contract: SOL_MINT,
    subject: amountSubject(1_000_000n, 6),
    to,
    valuation: usd(cents),
    ...over,
  };
}
